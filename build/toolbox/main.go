// Command gen-toolbox copies the body of images/ceph/toolbox.sh into the toolbox
// manifests that inline it, between their AUTOGENERATED marker lines.
package main

import (
	"fmt"
	"os"
	"strings"
)

const (
	sourceFile   = "images/ceph/toolbox.sh"
	sourceMarker = "# TOOLBOX_SCRIPT_BODY_BEGIN"
	beginMarker  = "# AUTOGENERATED from images/ceph/toolbox.sh; do not edit. Run: make gen-toolbox"
	endMarker    = "# END AUTOGENERATED"
)

var targetFiles = []string{
	"deploy/examples/toolbox.yaml",
	"deploy/examples/toolbox-operator-image.yaml",
	"deploy/charts/rook-ceph-cluster/templates/deployment.yaml",
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen-toolbox:", err)
		os.Exit(1)
	}
}

func run() error {
	body, err := readBody(sourceFile)
	if err != nil {
		return err
	}

	for _, target := range targetFiles {
		updated, err := spliceFile(target, body)
		if err != nil {
			return err
		}
		if updated {
			fmt.Println("gen-toolbox: updated", target)
		} else {
			fmt.Println("gen-toolbox: unchanged", target)
		}
	}
	return nil
}

// readBody returns the lines of path that follow its source marker.
func readBody(path string) ([]string, error) {
	content, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}

	lines := splitLines(string(content))
	marker, err := findMarker(path, lines, sourceMarker)
	if err != nil {
		return nil, err
	}

	body := lines[marker+1:]
	if len(body) > 0 && body[len(body)-1] == "" {
		body = body[:len(body)-1]
	}
	if len(body) == 0 {
		return nil, fmt.Errorf("%s: nothing follows %q", path, sourceMarker)
	}
	return body, nil
}

// spliceFile replaces the lines between path's markers with body, and reports whether
// that changed the file.
func spliceFile(path string, body []string) (bool, error) {
	info, err := os.Stat(path)
	if err != nil {
		return false, err
	}
	content, err := os.ReadFile(path)
	if err != nil {
		return false, err
	}

	lines := splitLines(string(content))
	begin, err := findMarker(path, lines, beginMarker)
	if err != nil {
		return false, err
	}
	end, err := findMarker(path, lines, endMarker)
	if err != nil {
		return false, err
	}
	if end < begin {
		return false, fmt.Errorf("%s: %q on line %d comes before %q on line %d",
			path, endMarker, end+1, beginMarker, begin+1)
	}

	spliced := make([]string, 0, begin+1+len(body)+len(lines)-end)
	spliced = append(spliced, lines[:begin+1]...)
	spliced = append(spliced, indentBody(body, leadingWhitespace(lines[begin]))...)
	spliced = append(spliced, lines[end:]...)

	updated := strings.Join(spliced, "\n")
	if updated == string(content) {
		return false, nil
	}
	//nolint:gosec // G703: path is one of the manifests listed above, not external input
	return true, os.WriteFile(path, []byte(updated), info.Mode().Perm())
}

// findMarker returns the index of the only line that equals marker once its indentation
// is stripped.
func findMarker(path string, lines []string, marker string) (int, error) {
	found := -1
	for i, line := range lines {
		if strings.TrimLeft(line, " \t") != marker {
			continue
		}
		if found >= 0 {
			return 0, fmt.Errorf("%s: duplicate marker %q on lines %d and %d", path, marker, found+1, i+1)
		}
		found = i
	}
	if found < 0 {
		return 0, fmt.Errorf("%s: missing marker %q", path, marker)
	}
	return found, nil
}

func indentBody(body []string, indent string) []string {
	indented := make([]string, len(body))
	for i, line := range body {
		if line == "" {
			continue
		}
		indented[i] = indent + line
	}
	return indented
}

func leadingWhitespace(line string) string {
	return line[:len(line)-len(strings.TrimLeft(line, " \t"))]
}

// splitLines keeps the empty element that follows a trailing newline, so that joining the
// lines again restores the file byte for byte.
func splitLines(content string) []string {
	return strings.Split(content, "\n")
}
