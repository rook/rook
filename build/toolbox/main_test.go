func TestLeadingWhitespace(t *testing.T) {
	tests := map[string]string{
		"      # marker": "      ",
		"\t# marker":     "\t",
		"# marker":       "",
		"":               "",
	}
	for line, want := range tests {
		if got := leadingWhitespace(line); got != want {
			t.Fatalf("leadingWhitespace(%q) = %q, want %q", line, got, want)
		}
	}
}
