func writeFile(t *testing.T, name, content string, mode os.FileMode) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(path, []byte(content), mode); err != nil {
		t.Fatal(err)
	}
	return path
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	content, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(content)
}

const carrier = `spec:
  command:
    - |
      # AUTOGENERATED from images/ceph/toolbox.sh; do not edit. Run: make gen-toolbox
      stale line
      # END AUTOGENERATED
  imagePullPolicy: IfNotPresent
`

func TestReadBody(t *testing.T) {
	tests := []struct {
		name    string
		content string
		want    []string
		wantErr string
	}{
		{
			name:    "body follows the marker",
			content: "# license\n\n# TOOLBOX_SCRIPT_BODY_BEGIN\n# inputs\n\necho hi\n",
			want:    []string{"# inputs", "", "echo hi"},
		},
		{
			name:    "no trailing newline",
			content: "# TOOLBOX_SCRIPT_BODY_BEGIN\necho hi",
			want:    []string{"echo hi"},
		},
		{
			name:    "missing marker",
			content: "# inputs\necho hi\n",
			wantErr: "missing marker",
		},
		{
			name:    "duplicate marker",
			content: "# TOOLBOX_SCRIPT_BODY_BEGIN\necho hi\n# TOOLBOX_SCRIPT_BODY_BEGIN\n",
			wantErr: "duplicate marker",
		},
		{
			name:    "empty body",
			content: "# license\n# TOOLBOX_SCRIPT_BODY_BEGIN\n",
			wantErr: "nothing follows",
		},
		{
			name:    "crlf line endings hide the marker",
			content: "# TOOLBOX_SCRIPT_BODY_BEGIN\r\necho hi\r\n",
			wantErr: "missing marker",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := readBody(writeFile(t, "toolbox.sh", tt.content, 0o755))
			switch {
			case tt.wantErr != "":
				if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
					t.Fatalf("got error %v, want one containing %q", err, tt.wantErr)
				}
			case err != nil:
				t.Fatal(err)
			case !slices.Equal(got, tt.want):
				t.Fatalf("got %q, want %q", got, tt.want)
			}
		})
	}
}

func TestSpliceFile(t *testing.T) {
	path := writeFile(t, "toolbox.yaml", carrier, 0o644)
	body := []string{"# inputs", "", "echo hi"}

	want := `spec:
  command:
    - |
      # AUTOGENERATED from images/ceph/toolbox.sh; do not edit. Run: make gen-toolbox
      # inputs

      echo hi
      # END AUTOGENERATED
  imagePullPolicy: IfNotPresent
`

	updated, err := spliceFile(path, body)
	if err != nil {
		t.Fatal(err)
	}
	if !updated {
		t.Fatal("first splice reported no change")
	}
	if got := readFile(t, path); got != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}
	for line := range strings.SplitSeq(want, "\n") {
		if line != strings.TrimRight(line, " \t") {
			t.Fatalf("line %q has trailing whitespace", line)
		}
	}

	updated, err = spliceFile(path, body)
	if err != nil {
		t.Fatal(err)
	}
	if updated {
		t.Fatal("second splice reported a change")
	}
	if got := readFile(t, path); got != want {
		t.Fatalf("second splice changed the file:\n%s", got)
	}
}

func TestSpliceFilePreservesMode(t *testing.T) {
	path := writeFile(t, "toolbox.yaml", carrier, 0o640)
	if _, err := spliceFile(path, []string{"echo hi"}); err != nil {
		t.Fatal(err)
	}

	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	if got := info.Mode().Perm(); got != 0o640 {
		t.Fatalf("got mode %v, want %v", got, os.FileMode(0o640))
	}
}

func TestSpliceFileErrors(t *testing.T) {
	tests := []struct {
		name    string
		content string
		wantErr string
	}{
		{
			name:    "missing begin marker",
			content: "spec:\n      # END AUTOGENERATED\n",
			wantErr: "missing marker",
		},
		{
			name:    "missing end marker",
			content: "spec:\n      # AUTOGENERATED from images/ceph/toolbox.sh; do not edit. Run: make gen-toolbox\n",
			wantErr: "missing marker",
		},
		{
			name:    "duplicate begin marker",
			content: carrier + "      # AUTOGENERATED from images/ceph/toolbox.sh; do not edit. Run: make gen-toolbox\n",
			wantErr: "duplicate marker",
		},
		{
			name:    "duplicate end marker",
			content: carrier + "      # END AUTOGENERATED\n",
			wantErr: "duplicate marker",
		},
		{
			name: "reversed markers",
			content: "spec:\n      # END AUTOGENERATED\n" +
				"      # AUTOGENERATED from images/ceph/toolbox.sh; do not edit. Run: make gen-toolbox\n",
			wantErr: "comes before",
		},
		{
			name:    "crlf line endings hide the markers",
			content: strings.ReplaceAll(carrier, "\n", "\r\n"),
			wantErr: "missing marker",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			path := writeFile(t, "toolbox.yaml", tt.content, 0o644)
			_, err := spliceFile(path, []string{"echo hi"})
			if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
				t.Fatalf("got error %v, want one containing %q", err, tt.wantErr)
			}
			if got := readFile(t, path); got != tt.content {
				t.Fatalf("file was modified despite the error:\n%s", got)
			}
		})
	}
}

